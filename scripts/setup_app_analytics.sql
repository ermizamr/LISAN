-- Run this in your Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)
-- It cleans up any misplaced test telemetry from the dataset refinement table,
-- and creates the dedicated app_analytics table with indexes and RLS.

-- 1. Purge any test telemetry rows from the dataset refinement table:
DELETE FROM public.community_validations 
WHERE domain = 'app_analytics' 
   OR tuple_id IN ('app_telemetry', 'telemetry_test', 'telemetry_event');

-- 2. Create the dedicated app_analytics table:
CREATE TABLE IF NOT EXISTS public.app_analytics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id TEXT NOT NULL,
    session_id TEXT,
    event_type TEXT NOT NULL,               -- 'translation', 'session_start', 'tts_played', 'scenario_selected', 'error'
    source_lang TEXT,                       -- 'amh', 'orm', 'tir', 'som', 'eng'
    target_lang TEXT,                       -- 'amh', 'orm', 'tir', 'som', 'eng'
    input_type TEXT,                        -- 'voice', 'text'
    mode TEXT,                              -- 'offline_nmt', 'offline_tm', 'server_api'
    latency_ms INTEGER DEFAULT 0,
    scenario TEXT,                          -- 'clinic', 'kebele', 'market', 'police', 'general', etc.
    platform TEXT,                          -- 'android', 'ios', 'linux', 'windows', 'web'
    app_version TEXT DEFAULT '1.0.0',
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- Index high-frequency query columns for real-time dashboard analytics
CREATE INDEX IF NOT EXISTS idx_app_analytics_created_at ON public.app_analytics (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_app_analytics_event_type ON public.app_analytics (event_type);
CREATE INDEX IF NOT EXISTS idx_app_analytics_device_id ON public.app_analytics (device_id);
CREATE INDEX IF NOT EXISTS idx_app_analytics_langs ON public.app_analytics (source_lang, target_lang);
CREATE INDEX IF NOT EXISTS idx_app_analytics_mode ON public.app_analytics (mode);

-- Enable Row Level Security (RLS)
ALTER TABLE public.app_analytics ENABLE ROW LEVEL SECURITY;

-- Allow anonymous app clients to send telemetry events
CREATE POLICY "Allow public inserts" ON public.app_analytics
    FOR INSERT
    WITH CHECK (true);

-- Allow public read access to analytics metrics for dashboard queries
CREATE POLICY "Allow public reads" ON public.app_analytics
    FOR SELECT
    USING (true);

-- Helpful aggregate view for dashboard query acceleration
CREATE OR REPLACE VIEW public.app_analytics_summary AS
SELECT
    COUNT(*) AS total_events,
    COUNT(DISTINCT device_id) AS unique_devices,
    COUNT(*) FILTER (WHERE event_type = 'translation') AS total_translations,
    COUNT(*) FILTER (WHERE mode = 'server_api') AS online_translations,
    COUNT(*) FILTER (WHERE mode IN ('offline_nmt', 'offline_tm')) AS offline_translations,
    COUNT(*) FILTER (WHERE input_type = 'voice') AS voice_translations,
    COUNT(*) FILTER (WHERE input_type = 'text') AS text_translations,
    ROUND(AVG(latency_ms) FILTER (WHERE event_type = 'translation'), 0) AS avg_latency_ms
FROM public.app_analytics;
